/**
 * artifact.test.ts
 *
 * Asserts that the creation bytecode embedded in SplitDistributorArtifact.ts
 * hashes to the expected keccak256, so any accidental mutation of the
 * bytecode constant is caught immediately.
 *
 * The expected hash is the one printed by `bun run export:artifact` from
 * the current forge build. If you recompile the contract and regenerate
 * the artifact (bun run export:artifact), update EXPECTED_KECCAK below.
 */

import { describe, it, expect } from 'vitest'
import { keccak256, toBytes } from 'viem'
import {
  SPLIT_DISTRIBUTOR_BYTECODE,
  SPLIT_DISTRIBUTOR_BYTECODE_KECCAK256,
} from '@/abi/SplitDistributorArtifact'

/**
 * Expected keccak256 of the creation bytecode.
 * Generated by: bun run export:artifact
 * Compiler: solc 0.8.28+commit.7893614a, EVM cancun, optimizer runs=200
 */
// Updated after enabling via_ir=true in foundry.toml (required for ScheduledSplit stack depth).
const EXPECTED_KECCAK256 = '0x160c99b64b4729c8149a3758f4511af3b5a72d6d40ec52028572988d36ef0ff0'

describe('SplitDistributor artifact', () => {
  it('creation bytecode starts with 0x', () => {
    expect(SPLIT_DISTRIBUTOR_BYTECODE.startsWith('0x')).toBe(true)
  })

  it('creation bytecode length is non-trivial (> 100 bytes)', () => {
    const byteLength = (SPLIT_DISTRIBUTOR_BYTECODE.length - 2) / 2
    expect(byteLength).toBeGreaterThan(100)
  })

  it('embedded keccak256 constant matches EXPECTED_KECCAK256', () => {
    expect(SPLIT_DISTRIBUTOR_BYTECODE_KECCAK256).toBe(EXPECTED_KECCAK256)
  })

  it('computed keccak256 of bytecode matches EXPECTED_KECCAK256', () => {
    const computed = keccak256(toBytes(SPLIT_DISTRIBUTOR_BYTECODE))
    expect(computed).toBe(EXPECTED_KECCAK256)
  })

  it('embedded keccak256 constant matches computed keccak256', () => {
    const computed = keccak256(toBytes(SPLIT_DISTRIBUTOR_BYTECODE))
    expect(SPLIT_DISTRIBUTOR_BYTECODE_KECCAK256).toBe(computed)
  })
})
