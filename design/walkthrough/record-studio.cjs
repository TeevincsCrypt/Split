const { chromium } = require('playwright')
const W = 1760, H = 800
;(async () => {
  const out = process.argv[2]
  const b = await chromium.launch({ proxy: { server: 'http://127.0.0.1:40401' } })
  const ctx = await b.newContext({ viewport: { width: W, height: H }, recordVideo: { dir: out, size: { width: W, height: H } } })
  const p = await ctx.newPage()
  const mark = (m) => console.log(`MARK ${m} ${Date.now()}`)
  mark('start')
  await p.goto('https://studio.arc.io/app/767489e9-b81c-4ccf-a5df-94881d408a4d', { waitUntil: 'domcontentloaded', timeout: 60000 })
  const ack = p.getByRole('button', { name: 'Acknowledge and continue' })
  await ack.waitFor({ state: 'visible', timeout: 30000 }).then(() => ack.click()).catch(() => console.log('no ack'))
  await p.waitForTimeout(2500)
  await p.getByRole('button', { name: 'Close sidebar' }).click().catch(() => console.log('no close'))
  await p.mouse.move(450, 400)
  for (let i = 0; i < 60; i++) { await p.mouse.wheel(0, -4000); await p.waitForTimeout(120) }
  await p.waitForTimeout(2500)
  mark('chat_top')
  await p.waitForTimeout(4000)
  // slow scroll through the conversation
  for (let i = 0; i < 140; i++) { await p.mouse.wheel(0, 60); await p.waitForTimeout(50) }
  mark('chat_scrolled')
  await p.getByRole('button', { name: /Code\s+Files and editor/ }).click()
  await p.waitForTimeout(2500)
  mark('code_open')
  const tree = p.locator('text=SplitDistributor.sol')
  // expand contracts folder entries are already open; click the file in the tree (last match is in the panel)
  const n = await tree.count(); console.log('matches', n)
  await tree.last().click().catch(e => console.log('file', e.message))
  await p.waitForTimeout(3000)
  mark('sd_open')
  await p.mouse.move(1350, 350)
  for (let i = 0; i < 60; i++) { await p.mouse.wheel(0, 50); await p.waitForTimeout(60) }
  await p.waitForTimeout(1500)
  await p.locator('text=ScheduledSplit.sol').last().click().catch(e => console.log('ss', e.message))
  await p.waitForTimeout(3500)
  mark('ss_open')
  await p.getByRole('button', { name: /^Contracts/ }).last().click().catch(e => console.log('contracts', e.message))
  await p.waitForTimeout(4500)
  mark('contracts_open')
  await p.screenshot({ path: `${out}/contracts.png` })
  await p.mouse.move(1250, 400)
  for (let i = 0; i < 40; i++) { await p.mouse.wheel(0, 50); await p.waitForTimeout(60) }
  await p.waitForTimeout(2500)
  mark('end')
  const buttons = await p.$$eval('button', els => els.map(e => (e.innerText || e.getAttribute('aria-label') || '').trim()).filter(t => t && t.length < 50))
  console.log(JSON.stringify([...new Set(buttons)].slice(-40)))
  await ctx.close(); await b.close()
})().catch(e => { console.error(e.message); process.exit(1) })
