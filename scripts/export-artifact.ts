/**
 * export-artifact.ts
 *
 * Reads the Foundry build artifact for SplitDistributor and writes
 * src/abi/SplitDistributorArtifact.ts with the ABI, creation bytecode,
 * deployed bytecode, and the keccak256 of the creation bytecode.
 *
 * Run: bun run export:artifact
 *
 * contracts/out/ is gitignored outside the sandbox, so the app imports
 * from the generated TS file rather than from contracts/out directly.
 */

import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'
import { keccak256, toBytes } from 'viem'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(__dirname, '..')

const ARTIFACT_PATH = path.join(ROOT, 'contracts/out/SplitDistributor.sol/SplitDistributor.json')
const OUTPUT_PATH = path.join(ROOT, 'src/abi/SplitDistributorArtifact.ts')

interface FoundryArtifact {
  abi: unknown[]
  bytecode: { object: string }
  deployedBytecode: { object: string; immutableReferences: Record<string, unknown> }
  methodIdentifiers: Record<string, string>
}

async function main() {
  if (!fs.existsSync(ARTIFACT_PATH)) {
    console.error(`Artifact not found at ${ARTIFACT_PATH}`)
    console.error('Run: bun run contracts:build   (forge build)')
    process.exit(1)
  }

  const raw = fs.readFileSync(ARTIFACT_PATH, 'utf8')
  const artifact = JSON.parse(raw) as FoundryArtifact

  const bytecode = artifact.bytecode.object as `0x${string}`
  const deployedBytecode = artifact.deployedBytecode.object as `0x${string}`
  const creationBytecodeKeccak256 = keccak256(toBytes(bytecode))

  const abi = JSON.stringify(artifact.abi, null, 2)
  const methodIds = JSON.stringify(artifact.methodIdentifiers, null, 2)

  const output = `// AUTO-GENERATED by scripts/export-artifact.ts — do not edit by hand.
// Regenerate: bun run export:artifact
// Source: contracts/SplitDistributor.sol  (contracts/out is gitignored)
// Compiler: solc 0.8.28, EVM cancun, optimizer runs=200

import type { Abi } from 'viem'

export const SPLIT_DISTRIBUTOR_ABI_JSON = ${abi} as const satisfies Abi

/** Creation (init) bytecode — includes constructor logic and constructor args encoding. */
export const SPLIT_DISTRIBUTOR_BYTECODE = ${JSON.stringify(bytecode)} as \`0x\${string}\`

/** Deployed (runtime) bytecode — what eth_getCode returns after deployment. */
export const SPLIT_DISTRIBUTOR_DEPLOYED_BYTECODE = ${JSON.stringify(deployedBytecode)} as \`0x\${string}\`

/**
 * keccak256 of SPLIT_DISTRIBUTOR_BYTECODE (the creation bytecode).
 * Displayed on the Deploy page so the user can verify before signing.
 */
export const SPLIT_DISTRIBUTOR_BYTECODE_KECCAK256 = ${JSON.stringify(creationBytecodeKeccak256)} as \`0x\${string}\`

/** Solidity method selectors — for reference / unused outside tooling. */
export const SPLIT_DISTRIBUTOR_METHOD_IDS = ${methodIds} as const
`

  fs.writeFileSync(OUTPUT_PATH, output, 'utf8')
  console.log(`Written: ${OUTPUT_PATH}`)
  console.log(`Creation bytecode keccak256: ${creationBytecodeKeccak256}`)
  console.log(`Bytecode length: ${bytecode.length} hex chars (${(bytecode.length - 2) / 2} bytes)`)
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
